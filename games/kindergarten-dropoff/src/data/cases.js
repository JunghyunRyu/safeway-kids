// 부모 유형 (안심 ❤️ + 기분 😊 균형으로)
export function parentType({ mood, heart, time }) {
  if (heart >= 75 && mood >= 65)
    return { name: '단단하고 다정한 부모', desc: '안전도 마음도 놓치지 않으려 매 순간 저울질했어요.' };
  if (heart >= 70 && time < 40)
    return { name: '아이를 먼저 보는 부모', desc: '시간을 내주더라도 아이의 마음과 안전을 앞에 두었어요.' };
  if (time >= 65 && heart < 55)
    return { name: '하루를 굴리는 부모', desc: '늦지 않게, 끊기지 않게 — 책임의 무게를 지고 가요.' };
  if (mood >= 70)
    return { name: '아이 웃음을 챙기는 부모', desc: '실랑이보다 웃음을, 다그침보다 공감을 골랐어요.' };
  return { name: '오늘도 애쓴 부모', desc: '정답 없는 아침을, 그래도 끝까지 함께 걸었어요.' };
}
